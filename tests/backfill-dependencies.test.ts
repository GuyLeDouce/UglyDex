import { expect, it, vi } from 'vitest';

const state = vi.hoisted(() => ({
  stages: new Map<string, Record<string, unknown>>(),
}));
vi.mock('../src/server/db', () => ({
  db: () => ({
    workerControl: { count: async () => 0 },
    productionStage: {
      findUnique: async ({ where }: { where: { stage: string } }) =>
        state.stages.get(where.stage),
      upsert: async ({
        where,
        create,
        update,
      }: {
        where: { stage: string };
        create: Record<string, unknown>;
        update: Record<string, unknown>;
      }) => {
        state.stages.set(
          where.stage,
          state.stages.has(where.stage)
            ? { ...state.stages.get(where.stage), ...update }
            : create,
        );
      },
      update: async ({
        where,
        data,
      }: {
        where: { stage: string };
        data: Record<string, unknown>;
      }) => {
        state.stages.set(where.stage, {
          ...state.stages.get(where.stage),
          ...data,
        });
      },
      findMany: async () => [...state.stages.values()],
    },
  }),
}));
vi.mock('pg', () => ({
  Pool: class {
    async connect() {
      return {
        query: async () => ({ rows: [{ acquired: true }] }),
        on() {},
        removeListener() {},
        release() {},
      };
    }
    async end() {}
  },
}));
vi.mock('../src/server/env', () => ({
  readEnv: () => ({ DATABASE_URL: 'postgresql://fixture' }),
}));
vi.mock('../src/server/production', () => ({
  migrationChecks: async () => [],
}));
vi.mock('../src/server/deployment', () => ({
  assertOperation: async () => {},
}));
vi.mock('../src/server/log', () => ({ log: vi.fn() }));
import { productionBackfill } from '../src/server/production-backfill';

it('drains progression generated by collection replay before verification, including across a pause', async () => {
  state.stages.clear();
  let pending = 0;
  let verified = false;
  const runner = async (stage: string) => {
    if (stage === 'collections') pending += 2;
    if (stage === 'progression') pending = 0;
    if (stage === 'verification') {
      expect(pending).toBe(0);
      verified = true;
    }
    return { complete: true, counts: {} };
  };
  await productionBackfill({ batches: 6, runner });
  expect(verified).toBe(false);
  await productionBackfill({ batches: 2, runner });
  expect(verified).toBe(true);
});
